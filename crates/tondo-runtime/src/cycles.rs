//! The cycle collector (language 16.7). Reference counting frees every
//! value except those on a cycle of references, and a cycle passes through
//! shared state that changed after it was made: values, closures and
//! `Ref`s never change. So the cells of shared state whose own state can
//! refer to them again register here, and a collection starts from them.
//!
//! It counts, for each object it reaches, the references that come from
//! other objects it reached. An object with more references than those is
//! held from elsewhere, by a task, a variable or the runtime, and stays
//! alive with everything it reaches; what remains is garbage. Its cells
//! give up their state, and reference counting frees the rest.
//!
//! The workers stop while it counts, at points where no task is between
//! two steps of following references (`tasks::stop_world`); the runtime's
//! other threads never follow the references of Tondo values, and one that
//! frees a registered cell waits for the collection to end.

use std::collections::HashMap;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Condvar, Mutex, MutexGuard, OnceLock};
use std::time::Duration;

/// Visits the references inside a value of one type; generated by the
/// compiler for the types whose values may be on a cycle.
pub type Visit = unsafe extern "C" fn(*mut u8, *mut Visitor);

/// The kinds of objects a collection follows, as compiled code names them.
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
#[repr(u8)]
pub enum Kind {
    /// The box of a recursive type; the payload's `Visit` is given.
    Box = 0,
    /// A `Ref`; the value's `Visit` is given.
    Ref = 1,
    /// An array or a deque; the element size and its `Visit` are given.
    Array = 2,
    /// A map or a set; the key's and the value's `Visit` are given.
    Map = 3,
    Fn = 4,
    /// A `Mutex`, `RwLock`, `Atomic` or `Once`.
    Sync = 5,
    /// A channel, which its `Receiver` is.
    Channel = 6,
    Sender = 7,
    Join = 8,
    Group = 9,
    SharedMap = 10,
    SharedQueue = 11,
    SharedStack = 12,
    SharedArray = 13,
    Reflect = 14,
}

impl Kind {
    fn from(code: u8) -> Option<Kind> {
        use Kind::*;
        [
            Box,
            Ref,
            Array,
            Map,
            Fn,
            Sync,
            Channel,
            Sender,
            Join,
            Group,
            SharedMap,
            SharedQueue,
            SharedStack,
            SharedArray,
            Reflect,
        ]
        .get(code as usize)
        .copied()
    }
}

// ---------------------------------------------------------------------------
// Registered cells
// ---------------------------------------------------------------------------

struct Registry {
    cells: HashMap<usize, Kind, std::hash::BuildHasherDefault<AddressHasher>>,
    /// Cells registered since the last collection, and how many start the
    /// next one.
    created: usize,
    threshold: usize,
}

static REGISTRY: std::sync::LazyLock<Mutex<Registry>> = std::sync::LazyLock::new(|| {
    Mutex::new(Registry { cells: HashMap::default(), created: 0, threshold: SMALLEST_THRESHOLD })
});

/// Collections never come closer than this many new cells apart.
const SMALLEST_THRESHOLD: usize = 1024;

fn registry() -> MutexGuard<'static, Registry> {
    REGISTRY.lock().unwrap_or_else(|e| e.into_inner())
}

/// Registers a new cell whose state may refer back to it.
pub(crate) fn remember(cell: *const u8, kind: Kind) {
    let mut registry = registry();
    registry.cells.insert(cell as usize, kind);
    registry.created += 1;
    // Far behind, this thread waits for the collector at its next safe
    // point, so that garbage cannot grow much faster than it goes.
    if registry.created >= BEHIND * registry.threshold {
        OWES.with(|owes| owes.set(true));
    }
    if registry.created == registry.threshold {
        drop(registry);
        wake_collector();
    }
}

/// How many thresholds of new cells make the threads that add more wait.
const BEHIND: usize = 4;

thread_local! {
    static OWES: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
}

/// Whether this thread waits for a collection at its next safe point.
pub(crate) fn owed() -> bool {
    OWES.with(|owes| owes.get())
}

/// Waits until the collector has caught up, out of Tondo code; not for
/// long, since a task that runs long without a safe point holds it back.
pub(crate) fn assist() {
    OWES.with(|owes| owes.set(false));
    let mut done = DONE.lock().unwrap_or_else(|e| e.into_inner());
    let seen = *done;
    let deadline = std::time::Instant::now() + Duration::from_millis(100);
    while *done == seen {
        let left = deadline.saturating_duration_since(std::time::Instant::now());
        if left.is_zero() {
            return;
        }
        done = CAUGHT_UP.wait_timeout(done, left).unwrap_or_else(|e| e.into_inner()).0;
    }
}

/// Collections finished, which `assist` waits for.
static DONE: Mutex<u64> = Mutex::new(0);
static CAUGHT_UP: Condvar = Condvar::new();

/// Unregisters a cell its last reference let go of, before its state goes;
/// waits while a collection runs.
pub(crate) fn forget(cell: *const u8) {
    registry().cells.remove(&(cell as usize));
}

// ---------------------------------------------------------------------------
// Visiting
// ---------------------------------------------------------------------------

/// An object reached: its address, what it is, how to visit it, its count
/// when reached, and the references to it from objects reached.
struct Node {
    address: usize,
    kind: Kind,
    a: usize,
    b: usize,
    rc: usize,
    internal: usize,
    edges: std::ops::Range<usize>,
    /// Held by something the counts do not show, such as a running task.
    held: bool,
    live: bool,
}

/// Hashes addresses for the node index: one multiplication, which is all
/// that distinct, aligned addresses need.
#[derive(Default)]
struct AddressHasher(u64);

impl std::hash::Hasher for AddressHasher {
    fn finish(&self) -> u64 {
        self.0
    }

    fn write(&mut self, _: &[u8]) {
        unreachable!("only addresses are hashed")
    }

    fn write_usize(&mut self, address: usize) {
        self.0 = (address as u64 >> 3).wrapping_mul(0x9e37_79b9_7f4a_7c15);
    }
}

type Index = HashMap<usize, usize, std::hash::BuildHasherDefault<AddressHasher>>;

/// What compiled code reports references to while a collection counts.
pub struct Visitor {
    nodes: Vec<Node>,
    index: Index,
    /// The objects each node refers to, by node.
    edges: Vec<usize>,
    /// The node being visited.
    current: usize,
}

const IMMORTAL: usize = usize::MAX;

impl Visitor {
    /// Runs `visit` on the value at `value`, which reports its references.
    pub(crate) unsafe fn visit(&mut self, visit: Option<Visit>, value: *mut u8) {
        if let Some(visit) = visit {
            unsafe { visit(value, self) };
        }
    }

    /// The node being visited is held by something the counts do not show.
    pub(crate) fn hold(&mut self) {
        self.nodes[self.current].held = true;
    }

    /// A reference from the node being visited to `object`.
    pub(crate) fn edge(&mut self, object: *const u8, kind: Kind, a: usize, b: usize) {
        if object.is_null() {
            return;
        }
        let rc = unsafe { (*(object as *const AtomicUsize)).load(Ordering::Acquire) };
        if rc == IMMORTAL {
            return;
        }
        let node = match self.index.get(&(object as usize)) {
            Some(&node) => node,
            None => self.add(object as usize, kind, a, b, rc),
        };
        self.edges.push(node);
    }

    fn add(&mut self, address: usize, kind: Kind, a: usize, b: usize, rc: usize) -> usize {
        let node = self.nodes.len();
        self.nodes.push(Node { address, kind, a, b, rc, internal: 0, edges: 0..0, held: false, live: false });
        self.index.insert(address, node);
        node
    }
}

/// `edge` for compiled code: a reference to `object` of the kind with the
/// code `kind`, and what visiting it needs.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tondo_rt_gc_edge(visitor: *mut Visitor, object: *const u8, kind: u8, a: usize, b: usize) {
    let Some(kind) = Kind::from(kind) else { return };
    unsafe { (*visitor).edge(object, kind, a, b) };
}

/// Reports the references inside an object.
unsafe fn children(visitor: &mut Visitor, address: usize, kind: Kind, a: usize, b: usize) {
    let object = address as *mut u8;
    let glue = |address: usize| (address != 0).then(|| unsafe { std::mem::transmute::<usize, Visit>(address) });
    unsafe {
        match kind {
            Kind::Box => visitor.visit(glue(a), super::box_payload(object)),
            Kind::Ref => visitor.visit(glue(a), super::ref_payload(object)),
            Kind::Array => super::visit_array(visitor, object, a, glue(b)),
            Kind::Map => super::visit_map(visitor, object, glue(a), glue(b)),
            Kind::Fn => super::visit_fn(visitor, object),
            Kind::Sync => super::sync::visit(visitor, object),
            Kind::Channel => super::tasks::visit_channel(visitor, object),
            Kind::Sender => super::tasks::visit_sender(visitor, object),
            Kind::Join => super::tasks::visit_join(visitor, object),
            Kind::Group => super::tasks::visit_group(visitor, object),
            Kind::SharedMap => super::shared::visit_map(visitor, object),
            Kind::SharedQueue => super::shared::visit_queue(visitor, object),
            Kind::SharedStack => super::shared::visit_stack(visitor, object),
            Kind::SharedArray => super::shared::visit_array(visitor, object),
            Kind::Reflect => super::reflect::visit(visitor, object),
        }
    }
}

/// What a garbage cell gave up, released once the workers run again.
pub(crate) type Taken = Box<dyn FnOnce()>;

/// Takes the state out of a garbage cell, which is then empty.
unsafe fn clear(node: &Node) -> Option<Taken> {
    let object = node.address as *mut u8;
    unsafe {
        match node.kind {
            Kind::Sync => super::sync::clear(object),
            Kind::Channel => super::tasks::clear_channel(object),
            Kind::Join => super::tasks::clear_join(object),
            Kind::SharedMap => super::shared::clear_map(object),
            Kind::SharedQueue => super::shared::clear_queue(object),
            Kind::SharedStack => super::shared::clear_stack(object),
            Kind::SharedArray => super::shared::clear_array(object),
            _ => None,
        }
    }
}

// ---------------------------------------------------------------------------
// Collecting
// ---------------------------------------------------------------------------

/// One collection at a time.
static COLLECTING: Mutex<()> = Mutex::new(());

/// How long a collection waits for the workers to stop before it gives up
/// and tries again later.
const STOP_TIMEOUT: Duration = Duration::from_millis(2);

/// Frees the garbage cycles; returns how many objects they held, or `None`
/// when the workers did not stop in time.
pub(crate) fn collect() -> Option<usize> {
    let _one = COLLECTING.lock().unwrap_or_else(|e| e.into_inner());
    if registry().cells.is_empty() {
        return Some(0);
    }
    // Stopped workers are never inside `forget`, which waits for the lock.
    if !super::tasks::stop_world(STOP_TIMEOUT) {
        return None;
    }
    let mut registry = registry();
    let mut visitor = Visitor { nodes: Vec::new(), index: Index::default(), edges: Vec::new(), current: 0 };
    for (&address, &kind) in &registry.cells {
        let rc = unsafe { (*(address as *const AtomicUsize)).load(Ordering::Acquire) };
        visitor.add(address, kind, 0, 0, rc);
    }
    // Every node's references, each node once; one whose count is zero is
    // being freed by another thread, which releases what it holds.
    let mut next = 0;
    while next < visitor.nodes.len() {
        let start = visitor.edges.len();
        let Node { address, kind, a, b, rc, .. } = visitor.nodes[next];
        if rc != 0 {
            visitor.current = next;
            unsafe { children(&mut visitor, address, kind, a, b) };
        }
        visitor.nodes[next].edges = start..visitor.edges.len();
        next += 1;
    }
    for &target in &visitor.edges {
        visitor.nodes[target].internal += 1;
    }
    // Held from outside: alive, with all it reaches.
    let held = |node: &Node| node.held || node.rc == 0 || node.rc > node.internal;
    let mut pending: Vec<usize> = (0..visitor.nodes.len()).filter(|&n| held(&visitor.nodes[n])).collect();
    while let Some(node) = pending.pop() {
        if std::mem::replace(&mut visitor.nodes[node].live, true) {
            continue;
        }
        let edges = visitor.nodes[node].edges.clone();
        pending.extend(visitor.edges[edges].iter().filter(|&&n| !visitor.nodes[n].live));
    }
    let freed = visitor.nodes.iter().filter(|n| !n.live).count();
    // The next collection comes once as many cells as live objects are
    // new, so that its work stays in proportion to the program's.
    registry.threshold = SMALLEST_THRESHOLD.max(visitor.nodes.len() - freed);
    registry.created = 0;
    super::tasks::resume_world();
    drop(registry);
    // Nothing reaches the garbage, so the workers may run meanwhile; no
    // other collection does. Releasing the cells' states frees the cycles,
    // and the cells unregister.
    let taken: Vec<Taken> = visitor.nodes.iter().filter(|n| !n.live).filter_map(|n| unsafe { clear(n) }).collect();
    for release in taken {
        release();
    }
    *DONE.lock().unwrap_or_else(|e| e.into_inner()) += 1;
    CAUGHT_UP.notify_all();
    Some(freed)
}

/// Collects until no garbage cycle remains, for the leak check at exit;
/// gives up after a while if the workers never stop.
pub(crate) fn collect_all() {
    for _ in 0..200 {
        match collect() {
            Some(0) => return,
            Some(_) => {}
            None => std::thread::sleep(Duration::from_millis(5)),
        }
    }
}

// ---------------------------------------------------------------------------
// The collector's thread
// ---------------------------------------------------------------------------

static WANTED: Mutex<bool> = Mutex::new(false);
static WANT: Condvar = Condvar::new();
static COLLECTOR: OnceLock<()> = OnceLock::new();

/// Asks the collector's thread to collect, starting it the first time.
fn wake_collector() {
    COLLECTOR.get_or_init(|| {
        super::tasks::spawn_thread(Some(256 * 1024), collector);
    });
    *WANTED.lock().unwrap_or_else(|e| e.into_inner()) = true;
    WANT.notify_one();
}

fn collector() {
    loop {
        let mut wanted = WANTED.lock().unwrap_or_else(|e| e.into_inner());
        while !*wanted {
            wanted = WANT.wait(wanted).unwrap_or_else(|e| e.into_inner());
        }
        *wanted = false;
        drop(wanted);
        // Workers busy for long hold the collection back; try again soon.
        while collect().is_none() {
            std::thread::sleep(Duration::from_millis(10));
        }
    }
}
